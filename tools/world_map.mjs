// Builds site/src/lib/world-map.ts: a small world map for the example form page, with the
// countries that have an example form drawn as separate shapes.
//
// Map data: Natural Earth 1:110m countries (public domain), via the world-atlas package.
// Run once when the map needs to change, from an empty folder:
//   npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.2
//   node /path/to/kinderform/tools/world_map.mjs /path/to/kinderform/site/src/lib/world-map.ts
import { createRequire } from "node:module"
import { writeFileSync } from "node:fs"

const require = createRequire(process.cwd() + "/")
const topojson = require("topojson-client")
const d3 = require("d3-geo")
const world = require("world-atlas/countries-110m.json")

const out = process.argv[2]
if (!out) throw new Error("Give the output path, for example site/src/lib/world-map.ts")

// ISO 3166 numeric codes, and a point for each country's label (lon, lat).
// Large countries carry their label in the middle. The European countries are too small for
// that: their labels sit out at sea ("callout"), joined to a point inside the country ("target")
// by a thin line. "align" says which side of the label touches the callout point.
const COUNTRIES = [
  { code: "uk", id: "826", name: "United Kingdom", label: [-24, 66], target: [-2, 54], align: "right" },
  { code: "us", id: "840", name: "United States", label: [-99, 37.5] },
  { code: "ca", id: "124", name: "Canada", label: [-112, 60] },
  { code: "au", id: "036", name: "Australia", label: [134, -25.5] },
  { code: "de", id: "276", name: "Germany", label: [36, 35], target: [10.4, 51.2], align: "left" },
  { code: "fr", id: "250", name: "France", label: [-24, 44.5], target: [2.4, 46.8], align: "right" },
  { code: "es", id: "724", name: "Spain", label: [-24, 33], target: [-3.7, 40.2], align: "right" },
  { code: "ie", id: "372", name: "Ireland", label: [-24, 55], target: [-8, 53.2], align: "right" },
  // The Netherlands is reached down the North Sea, so its line crosses no other highlighted country.
  { code: "nl", id: "528", name: "Netherlands", label: [-4, 79], target: [5.5, 52.3], align: "right" },
  { code: "nz", id: "554", name: "New Zealand", label: [160, -50], target: [172.5, -42], align: "right" },
  // Singapore is too small for the 1:110m map, so it is drawn as a dot at "dot".
  { code: "sg", id: "702", name: "Singapore", label: [96, -12], target: [103.8, 1.35], align: "right", dot: [103.8, 1.35] },
  // The Nordic labels sit in a column over Russia, 10 to 13 degrees apart, with Germany at the
  // bottom. Each line reaches its country without crossing another highlighted one. Sweden's
  // place, when it joins: label [36, 56.5], target [15.5, 60].
  { code: "no", id: "578", name: "Norway", label: [36, 80], target: [15, 67.5], align: "left" },
  { code: "fi", id: "246", name: "Finland", label: [36, 67], target: [26, 63.5], align: "left" },
  { code: "dk", id: "208", name: "Denmark", label: [36, 46], target: [10, 56.3], align: "left" },
]

const all = topojson.feature(world, world.objects.countries).features.filter((f) => f.id !== "010") // no Antarctica
const width = 1000
const projection = d3.geoNaturalEarth1().fitWidth(width, { type: "FeatureCollection", features: all })
const path = d3.geoPath(projection).digits(1)
const [[, y0], [, y1]] = path.bounds({ type: "FeatureCollection", features: all })
const top = Math.floor(y0)
const height = Math.ceil(y1 - top)

const shift = (d) => d.replace(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g, (_, x, y) => `${x},${+(+y - top).toFixed(1)}`)
const ids = new Set(COUNTRIES.map((c) => c.id))
const others = topojson.merge(
  world,
  world.objects.countries.geometries.filter((g) => !ids.has(g.id) && g.id !== "010"),
)
const pct = (v, of) => Math.round((1000 * v) / of) / 10
// A small circle, for a country too small to draw.
const dot = (lonLat, r = 3) => {
  const [x, y] = projection(lonLat).map((v) => +v.toFixed(1))
  return `M${x - r},${+(y - top).toFixed(1)}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0Z`
}

const countries = COUNTRIES.map((c) => {
  const feature = all.find((f) => f.id === c.id)
  if (!feature && !c.dot) throw new Error(`${c.name} is not in the map data: give it a dot`)
  const [x, y] = projection(c.label)
  const line = c.target
    ? [x, y - top, ...((([tx, ty]) => [tx, ty - top])(projection(c.target)))].map((v) => +v.toFixed(1))
    : null
  return {
    code: c.code,
    name: c.name,
    d: feature ? shift(path(feature)) : dot(c.dot),
    align: c.align ?? "center",
    // From the label's edge to a point inside the country, in map units.
    line,
    // Where the label sits, as a share of the map's width and height.
    x: pct(x, width),
    y: pct(y - top, height),
    // The same position as Tailwind classes, written out in full so Tailwind generates them
    // (the Content-Security-Policy rules out inline styles).
    pos: `left-[${pct(x, width)}%] top-[${pct(y - top, height)}%]`,
  }
})

const ts = `// Generated by tools/world_map.mjs from Natural Earth 1:110m countries (public domain).
// Do not edit by hand. Antarctica is left out.
export const MAP = { width: ${width}, height: ${height} } as const
export const LAND = ${JSON.stringify(shift(path(others)))}
export const MAP_COUNTRIES = ${JSON.stringify(countries, null, 2)} as const
`
writeFileSync(out, ts)
console.log(`Wrote ${out}: ${width}x${height}, ${Math.round(ts.length / 1024)} KB`)
for (const c of countries) console.log(c.code, c.x, c.y)
