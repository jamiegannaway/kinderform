"""Rebuild the visual summary at the top of docs/us-survey-plan.md from register/us/.

Run from the repository root:  python tools/us_summary.py
Check it is up to date:        python tools/us_summary.py --check
Standard library only. Everything shown is counted from the CSV files, so the
summary cannot drift from the data.
"""

import csv
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
US = ROOT / "register" / "us"
PAGE = ROOT / "docs" / "us-survey-plan.md"
START = "<!-- summary:start (generated by tools/us_summary.py; do not edit by hand) -->"
END = "<!-- summary:end -->"

# Tile map: one cell per state, laid out roughly where it sits on a map.
TILES = [
    ["AK", "", "", "", "", "", "", "", "", "", "ME"],
    ["", "", "", "", "", "", "", "", "", "VT", "NH"],
    ["WA", "ID", "MT", "ND", "MN", "IL", "WI", "MI", "NY", "RI", "MA"],
    ["OR", "NV", "WY", "SD", "IA", "IN", "OH", "PA", "NJ", "CT", ""],
    ["CA", "UT", "CO", "NE", "MO", "KY", "WV", "VA", "MD", "DE", ""],
    ["", "AZ", "NM", "KS", "AR", "TN", "NC", "SC", "DC", "", ""],
    ["", "", "", "OK", "LA", "MS", "AL", "GA", "", "", ""],
    ["HI", "", "", "TX", "", "", "", "", "FL", "", ""],
]

ADMIN_MARK = {"state_administered": "🟦", "county_administered": "🟧", "hybrid": "🟪"}


def read(name: str) -> list[dict]:
    with (US / name).open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def bar(value: int, top: int, width: int = 20) -> str:
    filled = round(width * value / top) if top else 0
    return "█" * filled + "░" * (width - filled)


def build() -> str:
    states = read("states.csv")
    doors = read("front-doors.csv")
    policies = read("policies.csv")
    forms = read("application-forms.csv")
    form_questions = read("form-questions.csv")
    app_questions = read("application-questions.csv")
    promises = read("response-promises.csv")

    every = [states, doors, policies, forms, form_questions, app_questions, promises]
    total_rows = sum(len(table) for table in every)
    verified = sum(1 for table in every for row in table if row.get("verification") == "verified")
    opened = sum(1 for table in every for row in table if row.get("evidence_level") in {"page_read", "form_read"})

    admin = {row["state_code"]: row["administration"] for row in states}
    doors_by_state = Counter(row["state_code"] for row in doors)
    policies_by_state = Counter(row["state_code"] for row in policies)
    private = [row for row in doors if row["sector"] in {"private_nonprofit", "private_for_profit"} and row["contracted"] == "no"]
    with_site = sum(1 for row in doors if row["website"])

    out: list[str] = []
    add = out.append
    add(START)
    add("")
    add(f"## At a glance")
    add("")
    add(f"*Counted from the files in [`register/us/`](../register/us/) on {date.today().isoformat()}. "
        "Every row is a lead to check until it is verified.*")
    add("")
    add("| 🗺️ Jurisdictions | 🚪 Front doors | 🏢 Private agencies | 📜 Policy rules | 📝 Application forms | ✅ Verified rows |")
    add("|:---:|:---:|:---:|:---:|:---:|:---:|")
    add(f"| **{len(states)}** | **{len(doors)}** | **{len(private)}** | **{len(policies)}** | **{len(forms)}** | **{verified} of {total_rows}** |")
    add(f"| 50 states and DC | {with_site} with their own page | phase 7 | {len({r['state_code'] for r in policies})} jurisdictions | "
        f"{sum(1 for r in forms if r['url'])} with a direct link | {opened} rows from an opened page |")
    add("")

    # Phase flow
    def status(done: bool, started: bool) -> str:
        return "done" if done else ("partial" if started else "todo")

    phases = [
        ("P1", "1 Structure", "done"),
        ("P2", "2 States", status(False, bool(states))),
        ("P3", "3 Front doors", status(False, bool(doors))),
        ("P4", "4 First-contact forms<br>and reply promises", status(False, bool(form_questions or promises))),
        ("P5", "5 Application forms", status(False, bool(forms or app_questions))),
        ("P6", "6 Policies", status(False, bool(policies))),
        ("P7", "7 Private agencies", status(False, bool(private))),
        ("P8", "8 Patterns summary", "todo"),
        ("P9", "9 Verification", status(False, verified > 0)),
    ]
    add("### Progress")
    add("")
    add("```mermaid")
    add("flowchart LR")
    for key, label, state in phases:
        add(f'    {key}["{label}"]:::{state}')
    add("    " + " --> ".join(key for key, _, _ in phases))
    add("    classDef done fill:#2e7d32,stroke:#1b5e20,color:#ffffff")
    add("    classDef partial fill:#f9a825,stroke:#f57f17,color:#000000")
    add("    classDef todo fill:#eceff1,stroke:#90a4ae,color:#37474f")
    add("```")
    add("")
    add("🟩 done · 🟨 first pass, unverified · ⬜ not started")
    add("")

    # Tile map
    add("### Who runs child welfare, and front doors found per state")
    add("")
    add("🟦 state-administered · 🟧 county-administered · 🟪 hybrid. The number is front doors in the register.")
    add("")
    width = len(TILES[0])
    add("|" + "|".join(" " for _ in range(width)) + "|")
    add("|" + "|".join(":-:" for _ in range(width)) + "|")
    for row in TILES:
        cells = []
        for code in row:
            if not code:
                cells.append(" ")
                continue
            mark = ADMIN_MARK.get(admin.get(code, ""), "⬜")
            cells.append(f"{mark} **{code}**<br>{doors_by_state.get(code, 0)}")
        add("|" + "|".join(cells) + "|")
    add("")

    # Front doors by level and by sector
    levels = Counter(row["level"] for row in doors)
    sectors = Counter(row["sector"] for row in doors)
    add("### Front doors")
    add("")
    add("```mermaid")
    add("pie showData title Front doors by level")
    for level in ("state", "regional", "county", "city", "tribal"):
        if levels.get(level):
            add(f'    "{level.capitalize()}" : {levels[level]}')
    add("```")
    add("")
    add("```mermaid")
    add("pie showData title Front doors by who runs them")
    names = {"public": "Public", "tribal": "Tribal", "private_nonprofit": "Private non-profit",
             "private_for_profit": "Private for-profit"}
    for sector, label in names.items():
        if sectors.get(sector):
            add(f'    "{label}" : {sectors[sector]}')
    add("```")
    add("")

    # Policy coverage by topic
    topics = Counter(row["topic"] for row in policies)
    if topics:
        add("### Policy rules found, by topic")
        add("")
        add("How many of the 51 jurisdictions have at least one rule recorded on each topic.")
        add("")
        per_topic = Counter()
        for topic in topics:
            per_topic[topic] = len({r["state_code"] for r in policies if r["topic"] == topic})
        add("| Topic | Jurisdictions | |")
        add("|---|---:|---|")
        for topic, count in per_topic.most_common(15):
            add(f"| `{topic}` | {count} | `{bar(count, len(states) or 51)}` |")
        add("")

    # Evidence
    add("### How far each row has been checked")
    add("")
    levels_seen = Counter(row.get("evidence_level", "") for table in every for row in table)
    add("| Evidence | Rows | |")
    add("|---|---:|---|")
    labels = {"search_result": "🔎 Search result only", "page_read": "📄 Page opened",
              "form_read": "📝 Form opened"}
    for key, label in labels.items():
        add(f"| {label} | {levels_seen.get(key, 0)} | `{bar(levels_seen.get(key, 0), total_rows)}` |")
    add(f"| ✅ Verified by a second person | {verified} | `{bar(verified, total_rows)}` |")
    add("")
    add(END)
    return "\n".join(out)


def main() -> int:
    page = PAGE.read_text(encoding="utf-8")
    summary = build()
    if START in page and END in page:
        before = page.split(START)[0]
        after = page.split(END, 1)[1]
        new = before + summary + after
    else:
        title, _, rest = page.partition("\n")
        new = title + "\n\n" + summary + "\n" + rest
    if "--check" in sys.argv:
        # Ignore the generation date when checking.
        strip = lambda text: "\n".join(l for l in text.splitlines() if not l.startswith("*Counted from"))
        if strip(new) != strip(page):
            print("docs/us-survey-plan.md summary is out of date: run python tools/us_summary.py")
            return 1
        print("Summary is up to date")
        return 0
    PAGE.write_text(new, encoding="utf-8")
    print("Updated docs/us-survey-plan.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
