"""Rebuild the visual summary at the top of docs/us-survey-plan.md from register/us/.

Run from the repository root:  python tools/us_summary.py
Check it is up to date:        python tools/us_summary.py --check
Standard library only. Charts are SVG files in docs/img/us/, built by
tools/us_charts.py. Every number on the page is counted from the CSV files, so
the summary cannot drift from the data. Each chart has a table view beneath it.
"""

import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import us_charts  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
US = ROOT / "register" / "us"
PAGE = ROOT / "docs" / "us-survey-plan.md"
START = "<!-- summary:start (generated by tools/us_summary.py; do not edit by hand) -->"
END = "<!-- summary:end -->"


def read(name: str) -> list[dict]:
    return us_charts.read(name)


def img(name: str, alt: str) -> str:
    return f'<p align="center"><img src="img/us/{name}" alt="{alt}" width="760"></p>'


def table_view(title: str, header: list[str], rows: list[tuple]) -> list[str]:
    out = [f"<details><summary>Table view: {title}</summary>", "", "| " + " | ".join(header) + " |",
           "|" + "|".join(["---"] + ["---:"] * (len(header) - 1)) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    out += ["", "</details>", ""]
    return out


def build() -> str:
    charts, t = us_charts.build()
    states = read("states.csv")
    doors = read("front-doors.csv")
    policies = read("policies.csv")
    forms = read("application-forms.csv")
    fq = read("form-questions.csv")
    aq = read("application-questions.csv")
    promises = read("response-promises.csv")
    verified = sum(r.get("verification") == "verified" for tbl in (states, doors, policies, forms, fq, aq, promises) for r in tbl)
    private = [d for d in doors if d["sector"].startswith("private") and d["contracted"] == "no"]

    out: list[str] = []
    add = out.append
    add(START)
    add("")
    add("## At a glance")
    add("")
    add(f"*Counted from the files in [`register/us/`](../register/us/) on {date.today().isoformat()}. "
        "Every row is a lead to check until a person has verified it. Charts follow your light or dark theme; "
        "each has a table view.*")
    add("")
    add(img("headline.svg", "Headline numbers for the US survey"))
    add("")
    add(img("map.svg", "Tile map of US states coloured by who runs child welfare, with front doors per state"))
    add("")
    by_admin = {}
    for s in states:
        by_admin.setdefault(s["administration"], []).append(s["state_code"])
    names = {"state_administered": "State-run", "county_administered": "County-run", "hybrid": "Mixed"}
    out += table_view("who runs child welfare", ["Model", "Jurisdictions", "Which"],
                      [(names[k], len(v), ", ".join(sorted(v))) for k, v in sorted(by_admin.items())])

    # Progress
    def status(done, started):
        return "done" if done else ("partial" if started else "todo")

    phases = [
        ("P1", "1 Structure", "done"),
        ("P2", "2 States", status(False, bool(states))),
        ("P3", "3 Front doors", status(False, bool(doors))),
        ("P4", "4 Enquiry forms<br>and reply promises", status(False, bool(fq or promises))),
        ("P5", "5 Application forms", status(False, bool(forms or aq))),
        ("P6", "6 Policies", status(False, bool(policies))),
        ("P7", "7 Private agencies", status(False, bool(private))),
        ("P8", "8 Patterns summary", status(False, True)),
        ("P9", "9 Verification", status(False, verified > 0)),
    ]
    add("### Progress")
    add("")
    add("```mermaid")
    add("flowchart LR")
    for key, label, state in phases:
        add(f'    {key}["{label}"]:::{state}')
    add("    " + " --> ".join(key for key, _, _ in phases))
    add("    classDef done fill:#008300,stroke:#005c00,color:#ffffff")
    add("    classDef partial fill:#eda100,stroke:#b37a00,color:#0b0b0b")
    add("    classDef todo fill:#eceff1,stroke:#90a4ae,color:#37474f")
    add("```")
    add("")
    add("Green: done. Amber: first pass, unverified. Grey: not started.")
    add("")
    add(img("evidence.svg", "How far each data set has been checked"))
    add("")
    out += table_view("how far each data set has been checked", ["Data set", "Rows", "Page or form opened", "Verified"],
                      t["evidence"])

    # Front doors
    add("## Who the front doors are")
    add("")
    add(img("levels.svg", "Front doors by level"))
    add("")
    add(img("sectors.svg", "Front doors by who runs them"))
    add("")
    out += table_view("front doors by level and by who runs them", ["Group", "Front doors"], t["levels"] + t["sectors"])

    # Patterns (phase 8)
    enquiry_rows, n_enquiry = t["enquiry"]
    app_rows, n_app = t["application"]
    share = dict(enquiry_rows)
    add("## What the data shows so far")
    add("")
    add("Neutral counts across front doors and states. No front door is scored or ranked, and every figure rests on "
        "unverified rows, so read these as early patterns to check, not findings.")
    add("")
    if enquiry_rows:
        add(f"- **Enquiry forms mostly ask for contact details.** All {n_enquiry} first-contact forms read ask for a name and an email address. "
            f"{share.get('Phone number', 0)}% ask for a phone number, {share.get('Street address', 0)}% for a street address "
            f"and {share.get('Date of birth or age', 0)}% for a date of birth or age.")
    if promises:
        days = sorted(v for _, v in t["promises"])
        add(f"- **Few front doors publish a reply time.** {len(t['promises'])} of the {sum(d['evidence_level'] in ('page_read', 'form_read') for d in doors)} "
            f"front-door pages opened state one, from {days[0]:g} to {days[-1]:g} days.")
    if t["min_age"]:
        common = max(t["min_age"], key=lambda r: r[1])
        add(f"- **The usual minimum age is {common[0]}.** {common[1]} of {sum(n for _, n in t['min_age'])} jurisdictions "
            "with a recorded figure set it; the others set "
            + " or ".join(str(a) for a, _ in t["min_age"] if a != common[0]) + ".")
    if t["training"]:
        add(f"- **Most states ask for 20 to 39 hours of training before licensing** "
            f"({sum(n for l, n in t['training'] if l.startswith(('20', '30')))} of {sum(n for _, n in t['training'])} with a figure).")
    if app_rows:
        add(f"- **Application forms ask far more than enquiry forms.** "
            f"{dict(app_rows).get('Date of birth or age', 0)}% of the {n_app} fillable forms read ask for a date of birth, "
            f"and most ask about relationships, work, education and who lives in the home.")
    add("")
    add("### What people are asked")
    add("")
    add(img("enquiry-topics.svg", "What first-contact enquiry forms ask"))
    add("")
    out += table_view("what enquiry forms ask", ["Topic", "Share of forms (%)"], enquiry_rows)
    add(img("application-topics.svg", "What application forms ask beyond contact details"))
    add("")
    out += table_view("what application forms ask", ["Topic", "Share of forms (%)"], app_rows)
    add("### What front doors promise")
    add("")
    if "promises.svg" in charts:
        add(img("promises.svg", "Published reply promises in days"))
        add("")
    out += table_view("published reply promises", ["Front door", "Days"], [(n, f"{d:g}") for n, d in t["promises"]])
    add("### Rules across states")
    add("")
    for name, alt, key, header in (("min-age.svg", "Minimum age to foster", "min_age", ["Minimum age", "Jurisdictions"]),
                                   ("training.svg", "Training before licensing", "training", ["Hours", "Jurisdictions"]),
                                   ("licence-term.svg", "How long a foster licence lasts", "licence_term", ["Licence term", "Jurisdictions"])):
        if name in charts:
            add(img(name, alt))
            add("")
        out += table_view(alt.lower(), header, t[key])
    add(END)
    return "\n".join(out)


def _splice(page: str, summary: str) -> str:
    if START in page and END in page:
        return page.split(START)[0] + summary + page.split(END, 1)[1]
    title, _, rest = page.partition("\n")
    return title + "\n\n" + summary + "\n" + rest


def stale() -> list[str]:
    """Return what is out of date: the page summary and/or chart files."""
    problems = []
    page = PAGE.read_text(encoding="utf-8")
    drop = lambda text: [l for l in text.splitlines() if not l.startswith("*Counted from")]
    if drop(_splice(page, build())) != drop(page):
        problems.append("docs/us-survey-plan.md summary")
    charts, _ = us_charts.build()
    for name, content in charts.items():
        path = us_charts.IMG / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            problems.append(f"docs/img/us/{name}")
    return problems


def main() -> int:
    if "--check" in sys.argv:
        problems = stale()
        if problems:
            print("Out of date: " + ", ".join(problems) + ". Run python tools/us_summary.py")
            return 1
        print("Summary is up to date")
        return 0
    charts, _ = us_charts.build()
    us_charts.write(charts)
    PAGE.write_text(_splice(PAGE.read_text(encoding="utf-8"), build()), encoding="utf-8")
    print(f"Updated docs/us-survey-plan.md and {len(charts)} charts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
