"""Write census/summary.md: counts from the intake-form census, with no services named.

Run: python tools/census_summary.py
Standard library only. Re-run after changing any census/*.csv file.
"""
import csv
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = ROOT / "census"


def load(name):
    with open(C / name, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


forms = {f["form_id"]: f for f in load("forms.csv")}
questions = load("questions.csv")
options = load("answer_options.csv")
guidance = load("guidance.csv")
taxonomy = {(t["category"], t["topic"]): t for t in load("taxonomy.csv")}

PUBLIC = {"regional_hub", "single_authority", "council", "council_consortium", "national_brand_council",
          "regional_service"}


def group(f):
    if f["operator_type"] == "independent_fostering_agency":
        return "Independent fostering agencies"
    if f["operator_type"] in ("regional_adoption_agency", "voluntary_adoption_agency"):
        return "Adoption agencies"
    if f["operator_type"] in PUBLIC:
        if f["service_type"] == "adoption":
            return "Council adoption services"
        return "Public fostering services"
    return "Other"


GROUPS = ["Public fostering services", "Independent fostering agencies", "Adoption agencies",
          "Council adoption services"]

# Forms that ask questions of the enquirer (not staff-only, not signposting, not vendor templates)
asked = defaultdict(list)
for q in questions:
    if q["category"] in ("staff_recorded",):
        continue
    asked[q["form_id"]].append(q)


MIN_QUESTIONS = 3  # forms with fewer recorded questions are too partial to count


def analysable(fid):
    f = forms[fid]
    return (len(asked.get(fid, [])) >= MIN_QUESTIONS and f["access_route"] != "signposting_only"
            and f["operator_type"] != "platform_vendor")


lines = ["# Intake-form census: summary counts", "",
         "Generated by `tools/census_summary.py` from the CSV files in this folder. "
         "It names no services. Counts describe what was **recorded**, which is not always "
         "everything a form asks: see the coverage notes in [README.md](README.md).", ""]

# Coverage
lines += ["## Coverage", "",
          "| Nation | Service | Primary forms | Secondary forms | Primary forms with questions recorded |",
          "|---|---|---|---|---|"]
cov = Counter()
for f in forms.values():
    if f["operator_type"] == "platform_vendor":
        continue
    key = (f["nation"], f["service_type"])
    cov[key + (f["form_stage"],)] += 1
    if f["form_stage"] == "primary" and analysable(f["form_id"]):
        cov[key + ("q",)] += 1
for nation, service in sorted({(k[0], k[1]) for k in cov}):
    lines.append(f"| {nation} | {service.replace('_', ' ')} | {cov[(nation, service, 'primary')]} | "
                 f"{cov[(nation, service, 'secondary')]} | {cov[(nation, service, 'q')]} |")
obs = Counter(f["observed"] for f in forms.values())
lines += ["", "How forms were seen: " + ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in sorted(obs.items())) + ".", ""]


# Topic frequency, primary
def topic_table(stage, groups):
    denom = {g: [fid for fid in asked if analysable(fid) and forms[fid]["form_stage"] == stage
                 and group(forms[fid]) == g] for g in groups}
    groups = [g for g in groups if denom[g]]
    asks = defaultdict(lambda: defaultdict(set))
    req = defaultdict(lambda: defaultdict(set))
    for g in groups:
        for fid in denom[g]:
            for q in asked[fid]:
                k = (q["category"], q["topic"])
                asks[k][g].add(fid)
                if q["required"] == "yes":
                    req[k][g].add(fid)
    head = "| Category | Topic | " + " | ".join(f"{g} (n={len(denom[g])})" for g in groups) + " |"
    out = [head, "|---|---|" + "---|" * len(groups)]
    order = sorted(asks, key=lambda k: (-sum(len(asks[k][g]) for g in groups), k))
    for k in order:
        cells = []
        for g in groups:
            a, r = len(asks[k][g]), len(req[k][g])
            cells.append(f"{a} ({r} req)" if a else "–")
        out.append(f"| {k[0]} | {k[1]} | " + " | ".join(cells) + " |")
    return out


lines += ["## What primary forms ask", "",
          "Number of forms that ask about each topic, and in brackets how many make it required. "
          "Forms that share a template are counted once. Forms with fewer than three questions "
          "recorded are left out of these tables.", ""]
lines += topic_table("primary", GROUPS)
lines += ["", "## What secondary forms ask", "",
          "Secondary forms are almost never published, so these come mostly from procedure manuals "
          "and privacy notices. Required status is usually unknown.", ""]
lines += topic_table("secondary", GROUPS)

# Sensitive topics on primary forms
lines += ["", "## Sensitive or gate topics on primary forms", "",
          "| Sensitivity | Forms asking | Of which required |", "|---|---|---|"]
sens = defaultdict(set)
sens_req = defaultdict(set)
for fid, qs in asked.items():
    if not analysable(fid) or forms[fid]["form_stage"] != "primary":
        continue
    for q in qs:
        s = taxonomy[(q["category"], q["topic"])]["sensitivity"]
        if s in ("none", "personal_identifier", "free_text"):
            continue
        sens[s].add(fid)
        if q["required"] == "yes":
            sens_req[s].add(fid)
for s in sorted(sens):
    lines.append(f"| {s.replace('_', ' ')} | {len(sens[s])} | {len(sens_req[s])} |")

# Guidance
lines += ["", "## Guidance around primary forms", "",
          "Forms with a guidance row of each type, split by whether the guidance was found. "
          "A form with no row for a type was not checked for it.", "",
          "| Guidance type | Found | Checked and not found |", "|---|---|---|"]
gp = defaultdict(set)
gn = defaultdict(set)
for gr in guidance:
    if forms[gr["form_id"]]["form_stage"] != "primary":
        continue
    (gp if gr["present"] == "yes" else gn)[gr["guidance_type"]].add(gr["form_id"])
for t in sorted(set(gp) | set(gn), key=lambda t: (-len(gp[t]), t)):
    lines.append(f"| {t.replace('_', ' ')} | {len(gp[t])} | {len(gn[t] - gp[t])} |")

mk = Counter(gr["value"] for gr in guidance if gr["guidance_type"] == "marketing_consent" and gr["value"])
lines += ["", "Marketing consent handling where recorded: " +
          ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in sorted(mk.items())) + ".", ""]
rt = Counter(gr["value"] for gr in guidance if gr["guidance_type"] == "response_time" and gr["present"] == "yes")
lines += [f"Concrete response times found on {sum(rt.values())} primary forms or their pages: " +
          "; ".join(f"{k} ({v})" for k, v in sorted(rt.items())) + ".", ""]

lines += ["## Totals", "",
          f"{len(forms)} forms, {len(questions)} questions, {len(options)} answer options, "
          f"{len(guidance)} guidance rows, {len(taxonomy)} taxonomy topics.", ""]

(C / "summary.md").write_text("\n".join(lines), encoding="utf-8")
print("Wrote census/summary.md")
