// Compiles ../schema/enquiry-submission.schema.json into a standalone validator
// at build time, so the browser never needs eval() and the page's
// Content-Security-Policy can stay strict (no 'unsafe-eval').
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import Ajv2020 from "ajv/dist/2020.js"
import standaloneCode from "ajv/dist/standalone/index.js"

const here = dirname(fileURLToPath(import.meta.url))
const schemaPath = resolve(here, "../../schema/enquiry-submission.schema.json")
const out = resolve(here, "../src/generated/validate-submission.js")

const schema = JSON.parse(readFileSync(schemaPath, "utf-8"))
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } })
const validate = ajv.compile(schema)
// Ajv's standalone output still calls require() for a few runtime helpers.
// Rewrite those into ES imports so the module runs in the browser.
let code = standaloneCode(ajv, validate)
const imports = []
code = code.replace(/require\("([^"]+)"\)/g, (_, mod) => {
  const name = `__rt${imports.length}`
  // Node and Vite expose a CommonJS module's default export differently.
  imports.push(
    `import * as ${name}_ns from "${mod}.js";\n` +
      `const ${name} = { default: typeof ${name}_ns.default === "function" ? ${name}_ns.default : ${name}_ns.default.default };`,
  )
  return name
})
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, "// Generated by scripts/compile-validators.mjs. Do not edit.\n" + imports.join("\n") + "\n" + code.replace(/^"use strict";/, ""))
console.log("Compiled validator ->", out)
